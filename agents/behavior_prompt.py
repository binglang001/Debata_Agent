# 3) HUMAN_CHAT_PATTERNS —— priority="high"，真人聊天形态规则
#
#    基于对真实微信聊天记录（30+ 不同关系样本）的方法论提炼。
#    这是把 AI 从"客服腔"拉到"真人腔"最关键的一段。
