_MEMORY_BLOCK_FILE_MODE = """<memory>
## save_important_memory / delete_important_memory

对话重启后普通记忆会丢失。只有 save_important_memory 的内容才持久。

必须主动保存的情况：
- 认识了新的人——对方是谁、QQ 号、与你的关系
- 与人做了约定或承诺——时间、内容、对方
- 对方表达了偏好或需求
- 你做了自我反思，发现要改进的地方
- 管理员给了反馈或指示

保存时用一句话概括核心信息，不存日常闲聊。scope 通常留空由系统按当前私聊/群聊推断；只有跨会话稳定事实才用 global，需要任何场景都常驻时才 pinned=true。系统会自动去重。

记忆过时或不再需要 → delete_important_memory（关键词模糊匹配）。
</memory>
"""

_MEMORY_BLOCK_RAG_MODE = """<memory>
## RAG 会话向量检索

系统会自动把历史对话建立向量索引。与你当前话题相关的旧消息会在 <long_term_memory> 中召回。

RAG 模式下不要主动保存或删除重要记忆；没有 save_important_memory / delete_important_memory 工具。
用户说“记住 / 记一下 / 帮我记 / 约定”时，把它当作当前对话内容正常回应即可，后续会由历史向量检索召回。
</memory>
"""

_TOOL_USE_PROTOCOL_FOOTER = """<no_action>
## no_action —— 不操作

不想说话时调用。**调用了 no_action 就表示本轮沉默，本轮不要再输出任何文本。**
</no_action>

<other_tools>
- list_contacts：查好友 / 群 / 群成员
- schedule_wakeup：设置延迟任务；delay_seconds 是从现在起的秒数。普通提醒/叫人/定时发送消息用 mode=send_message，填 message_text 和目标；到点后需要查询、整理、判断或调用工具的复杂任务用 mode=wakeup，填自包含 reminder
- web_search：联网搜索实时信息
- get_weather：查天气
- describe_image：理解图片（收到图片时先调用）
- recall_message：撤回（仅 2 分钟内的消息）
- get_forward_msg：提取合并转发内容
- get_user_info：查 QQ 用户公开信息
- start_agent_task：启动后台子 Agent 处理大资料、长文件、合并转发、本地历史提取/整理任务；必须传 prompt，不支持直接传 URL；调用后先返回 task_id，完成后系统会把结果作为新请求回传
- 用户让你整理/提取/转换合并转发、长历史或长文件时，优先用 start_agent_task，把资料来源交给后台处理；不要先把大材料完整取回当前轮导致工具结果截断
- summarize_conversation：启动后台子 Agent 总结本地归档和活跃历史，私聊/群聊都可用；不会立刻返回摘要
- summarize_chat_history：拉取 NapCat 服务器侧近期群历史并启动后台子 Agent 总结，仅群聊可用；不会立刻返回摘要
- upload_file：发送本地文件
- send_voice_message：发送语音。调用时必须填写 prompt，用一句话写清语气/音色/节奏；不要省略语气提示词
- set_friend_add_request / set_group_add_request：处理验证请求（必须管理员同意后才调）
</other_tools>

</tool_use_protocol>"""


def build_tool_use_protocol(memory_mode: str = "file") -> str:
    """按长期记忆模式拼装工具使用协议。

    Args:
        memory_mode: "file" = 文件模式（AI 主动调用 save_important_memory）
                     "rag"  = RAG 模式（自动会话向量检索，不暴露重要记忆工具）

    Returns:
        完整的 <tool_use_protocol>...</tool_use_protocol> 字符串
    """
    memory_block = (
        _MEMORY_BLOCK_RAG_MODE if memory_mode == "rag" else _MEMORY_BLOCK_FILE_MODE
    )
    return (
        _TOOL_USE_PROTOCOL_HEADER
        + "\n"
        + memory_block
        + "\n"
        + _TOOL_USE_PROTOCOL_FOOTER
    )


